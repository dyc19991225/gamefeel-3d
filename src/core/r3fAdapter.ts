import type { Locale, RecipeDefinition } from './types';

function toPascal(id: string): string {
  return id
    .split('-')
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('');
}

/**
 * Generates an idiomatic React Three Fiber (@react-three/fiber) hook + component wrapper
 * around the recipe's standalone TypeScript logic, enforcing clamped rawDt & useFrame best practices.
 */
export function generateR3fSnippet(recipe: RecipeDefinition, params: Record<string, number>): string {
  const pascal = toPascal(recipe.id);
  const coreSnippet = recipe.generateCode(params);
  const paramEntries = Object.entries(params)
    .map(([k, v]) => `  ${k} = ${v},`)
    .join('\n');

  return `// React Three Fiber (@react-three/fiber) Wrapper — ${recipe.badge}: ${recipe.title.en}
import { useRef, useImperativeHandle, forwardRef } from 'react';
import { useFrame, useThree } from '@react-three/fiber';
import * as THREE from 'three';

${coreSnippet}

export interface ${pascal}Props {
${Object.keys(params)
  .map((k) => `  ${k}?: number;`)
  .join('\n')}
  children?: React.ReactNode;
}

export interface ${pascal}Handle {
  trigger: () => void;
}

export const ${pascal}Rig = forwardRef<${pascal}Handle, ${pascal}Props>(function ${pascal}Rig(
  {
${paramEntries}
    children,
  },
  ref
) {
  const groupRef = useRef<THREE.Group>(null!);
  const { camera } = useThree();
  const impulseRef = useRef(0);

  useImperativeHandle(ref, () => ({
    trigger() {
      impulseRef.current = 1;
    },
  }));

  useFrame((_state, rawDelta) => {
    const dt = Math.min(rawDelta, 0.05); // Rule #3: Always clamp R3F delta!
    if (!groupRef.current) return;
    if (impulseRef.current > 0) {
      impulseRef.current = Math.max(0, impulseRef.current - dt * 6);
    }
    void camera;
  });

  return <group ref={groupRef}>{children}</group>;
});
`;
}

/**
 * Bundles multiple user-selected recipes into a single zero-dependency TypeScript Starter Kit (`gamefeel-kit.ts`).
 */
export function buildFeelKitBundle(
  selected: RecipeDefinition[],
  paramStore: Record<string, Record<string, number>>
): string {
  const header = `/**
 * ============================================================================
 * gamefeel-kit.ts — Custom Zero-Asset 3D Game-Feel Bundle (${selected.length} Recipes)
 * Generated by gamefeel-3d Studio (https://github.com/dyc19991225/gamefeel-3d)
 * ============================================================================
 */
import * as THREE from 'three';

/** Shared Frame-Rate Independent Smoothing & Dual-Clock Utilities */
export function damp(current: number, target: number, lambda: number, dt: number): number {
  return THREE.MathUtils.lerp(current, target, 1 - Math.exp(-lambda * Math.min(dt, 0.05)));
}

export class FeelDualClock {
  private hitstop = 0;
  public triggerHitstop(sec: number): void { this.hitstop = Math.max(this.hitstop, sec); }
  public step(rawDelta: number): { rawDt: number; scaledDt: number } {
    const rawDt = Math.min(rawDelta, 0.05);
    if (this.hitstop > 0) {
      this.hitstop = Math.max(0, this.hitstop - rawDt);
      return { rawDt, scaledDt: rawDt * 0.02 };
    }
    return { rawDt, scaledDt: rawDt };
  }
}
`;

  const blocks = selected.map((r, idx) => {
    const p: Record<string, number> = {};
    for (const def of r.params) {
      p[def.key] = paramStore[r.id]?.[def.key] ?? def.defaultValue;
    }
    // Strip duplicate import * as THREE lines inside individual snippets if any
    const cleanCode = r
      .generateCode(p)
      .replace(/^import \* as THREE from ['"]three['"];?\r?\n?/gm, '')
      .replace(/\bexport /g, `export `);
    return `// ----------------------------------------------------------------------------\n// [${idx + 1}/${selected.length}] ${r.badge} · ${r.title.en} (${r.title.zh})\n// ----------------------------------------------------------------------------\n${cleanCode}`;
  });

  return `${header}\n${blocks.join('\n\n')}\n`;
}

/**
 * Builds a combined multi-recipe `$gamefeel-3d` super-prompt for Codex / Claude Code / Antigravity.
 */
export function buildCombinedSkillPrompt(selected: RecipeDefinition[], locale: Locale): string {
  if (locale === 'zh') {
    const bullets = selected
      .map(
        (r, i) =>
          `${i + 1}. [${r.badge} ${r.title.zh}]：${r.agentPrompt.zh.replace(/^使用 gamefeel-3d 技能：/, '')}`
      )
      .join('\n');
    return `$gamefeel-3d 请按双时钟规范（rawDt / scaledDt 分离）与零外部资产原则，一次性为我的 Three.js 游戏集成以下 ${selected.length} 项手感配方：\n${bullets}`;
  }
  const bullets = selected
    .map(
      (r, i) =>
        `${i + 1}. [${r.badge} ${r.title.en}]: ${r.agentPrompt.en.replace(/^Use gamefeel-3d skill:\s*/i, '')}`
    )
    .join('\n');
  return `$gamefeel-3d Following the dual-clock (rawDt vs scaledDt) and zero-asset rules, integrate these ${selected.length} game-feel recipes into my Three.js project:\n${bullets}`;
}
